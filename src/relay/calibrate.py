"""Fits the stand-in's behaviour to measurements of the real service.

Reads ``raw/groq_calls.jsonl`` (every real attempt) and writes:

* ``config/standin_calibration.yaml``: per-model latency parameters
  (lognormal TTFT median and sigma, prefill cost per 1k prompt tokens,
  decode tokens/s) and the limits seen in response headers;
* ``raw/replay.jsonl``: successful real replies keyed by message hash, so the
  stand-in can return real content for prompts it has seen;
* a printed comparison of real versus fitted quantiles, so the fit can be
  judged rather than trusted.

Typical usage example:

    uv run python -m relay.calibrate
"""

from __future__ import annotations

import json
import math
import statistics
from collections import defaultdict

import numpy as np
import yaml

from relay.config import CONFIG_DIR, RAW_DIR

CALLS = RAW_DIR / "groq_calls.jsonl"
OUT = CONFIG_DIR / "standin_calibration.yaml"
REPLAY = RAW_DIR / "replay.jsonl"


def _pct(xs: list[float], p: float) -> float:
    """Nearest-rank percentile.

    Args:
        xs: Values (any order, non-empty).
        p: Percentile in (0, 100].

    Returns:
        The value at rank ``ceil(p/100 * n)``.
    """
    s = sorted(xs)
    return s[max(0, math.ceil(p / 100 * len(s)) - 1)]


def fit_model(calls: list[dict]) -> dict:
    """Fits latency parameters for one model's successful calls.

    TTFT is modelled as ``lognormal(median, sigma) + slope * prompt_tokens``;
    the slope comes from a least-squares fit of TTFT on prompt tokens and is
    clamped at zero. Decode speed is completion tokens over streaming time.

    Args:
        calls: Successful attempts for one model.

    Returns:
        Fitted parameters and fit diagnostics.
    """
    ttft = np.array([c["ttft_ms"] for c in calls])
    tin = np.array([c["tokens_in"] for c in calls])
    slope = 0.0
    if len(set(tin.tolist())) > 2:
        slope = max(0.0, float(np.polyfit(tin, ttft, 1)[0]))
    resid = np.maximum(1.0, ttft - slope * tin)
    logs = np.log(resid)
    tps = [
        c["tokens_out"] / ((c["total_ms"] - c["ttft_ms"]) / 1000)
        for c in calls
        if c["tokens_out"] > 8 and c["total_ms"] - c["ttft_ms"] > 5
    ]
    out = {
        "ttft_median_ms": round(float(np.exp(np.median(logs))), 1),
        "ttft_sigma": round(float(np.std(logs)), 3),
        "prefill_ms_per_1k": round(slope * 1000, 2),
    }
    if len(tps) >= 3:
        lt = np.log(tps)
        out["decode_tps_median"] = round(float(np.exp(np.median(lt))), 1)
        out["decode_tps_sigma"] = round(float(np.std(lt)), 3)
    return out


def main() -> None:
    """Fits every model seen in the real-call log and writes outputs."""
    calls = []
    if CALLS.exists():
        with open(CALLS) as f:
            calls = [json.loads(line) for line in f]
    if not calls:
        raise SystemExit(f"no real calls in {CALLS}: run relay.probes first")
    by_model: dict[str, list[dict]] = defaultdict(list)
    limits: dict[str, dict] = defaultdict(dict)
    statuses: dict[str, dict] = defaultdict(lambda: defaultdict(int))
    for c in calls:
        statuses[c["model"]][c["status"]] += 1
        h = c.get("headers") or {}
        if "x-ratelimit-limit-tokens" in h:
            limits[c["model"]]["tpm"] = int(float(h["x-ratelimit-limit-tokens"]))
        if "x-ratelimit-limit-requests" in h:
            limits[c["model"]]["rpd"] = int(float(h["x-ratelimit-limit-requests"]))
        if c["status"] == "ok" and c.get("ttft_ms"):
            by_model[c["model"]].append(c)

    per_model = {}
    print(f"{'model':28s} {'n':>4s} {'real p50/p95 ttft':>20s} {'fit p50/p95':>14s}  params")
    rng = np.random.default_rng(0)
    for model, cs in sorted(by_model.items()):
        if len(cs) < 5:
            print(f"{model:28s} {len(cs):4d}  (too few calls to fit)")
            continue
        fit = fit_model(cs)
        per_model[model] = fit
        real = [c["ttft_ms"] for c in cs]
        sim = [
            fit["ttft_median_ms"] * math.exp(rng.normal(0, fit["ttft_sigma"]))
            + fit["prefill_ms_per_1k"] * c["tokens_in"] / 1000
            for c in cs
            for _ in range(20)
        ]
        print(
            f"{model:28s} {len(cs):4d} {_pct(real, 50):9.0f}/{_pct(real, 95):<9.0f} "
            f"{_pct(sim, 50):6.0f}/{_pct(sim, 95):<6.0f}  {fit}"
        )
    for model, st in statuses.items():
        print(f"  statuses {model}: {dict(st)}")

    calib = {"latency": {"per_model": per_model}}
    if limits:
        calib["limits"] = {"per_model": {m: dict(v) for m, v in limits.items()}}
    with open(OUT, "w") as f:
        f.write("# Generated by `python -m relay.calibrate` from raw/groq_calls.jsonl.\n")
        yaml.safe_dump(calib, f, sort_keys=True)

    seen = {}
    for c in calls:
        if c["status"] == "ok" and c.get("msg_key") and c.get("text"):
            seen[c["msg_key"]] = c["text"]
    with open(REPLAY, "w") as f:
        f.writelines(
            json.dumps({"key": k, "text": text}, ensure_ascii=False) + "\n"
            for k, text in seen.items()
        )
    lat = [c["total_ms"] for cs in by_model.values() for c in cs]
    print(
        f"\nwrote {OUT.name} ({len(per_model)} models) and {len(seen)} replay entries; "
        f"median real total {statistics.median(lat):.0f} ms"
    )


if __name__ == "__main__":
    main()
